"""The vault a browser built must be one this server accepts.

The CLI and the web console both write the same vault record, and the server
verifies it with PyNaCl against a payload duplicated in Go, Python, and
TypeScript. Only a fixture produced by the other implementation proves the
three still agree.

``tests/fixtures/browser_vault.json`` is generated by the website's
``scripts/vault-parity.ts`` and must not be hand-edited.
"""

import json
import pathlib

from django.test import SimpleTestCase

from apps.accounts.vault import validate_vault

FIXTURE = pathlib.Path(__file__).parent / "tests" / "fixtures" / "browser_vault.json"
FIXTURE_V2 = pathlib.Path(__file__).parent / "tests" / "fixtures" / "browser_vault_v2.json"


class BrowserVaultCompatibilityTests(SimpleTestCase):
    def setUp(self):
        self.fixture = json.loads(FIXTURE.read_text())

    def test_browser_vault_passes_server_validation(self):
        # validate_vault runs the same PyNaCl proof check the API enforces, so
        # this fails if the browser's payload layout or signing drifted.
        validate_vault(self.fixture["vault"], user_id=self.fixture["user_id"])

    def test_browser_vault_carries_both_factors(self):
        types = {envelope["type"] for envelope in self.fixture["vault"]["envelopes"]}
        self.assertEqual(types, {"password", "recovery"})

    def test_tampered_browser_vault_is_rejected(self):
        tampered = json.loads(FIXTURE.read_text())
        tampered["vault"]["envelopes"][0]["ciphertext"] = "AAAA"
        with self.assertRaises(Exception):
            validate_vault(tampered["vault"], user_id=tampered["user_id"])


class BrowserVaultV2CompatibilityTests(SimpleTestCase):
    """The v2 split-share vault the browser builds must be one this server accepts.

    The fixture is generated by scripts/vault-parity.ts (create-v2); the export
    key it carries is test-only and is never stored in production. The proof and
    the opaque-share envelope are what the server validates structurally.
    """

    def setUp(self):
        self.fixture = json.loads(FIXTURE_V2.read_text())

    def test_browser_v2_vault_passes_server_validation(self):
        # A v2 vault (password + opaque + recovery) must validate: correct
        # proof, the opaque envelope's KDF, and the version-2 policy checks.
        validate_vault(self.fixture["vault"], user_id=self.fixture["user_id"])

    def test_browser_v2_vault_carries_split_shares(self):
        types = {envelope["type"] for envelope in self.fixture["vault"]["envelopes"]}
        self.assertEqual(types, {"password", "opaque", "recovery"})

    def test_browser_v2_vault_names_min_client_version(self):
        self.assertEqual(self.fixture["vault"]["version"], 2)
        self.assertEqual(self.fixture["vault"]["min_client_version"], "4.1.0")

    def test_tampered_browser_v2_vault_is_rejected(self):
        tampered = json.loads(FIXTURE_V2.read_text())
        tampered["vault"]["envelopes"][0]["ciphertext"] = "AAAA"
        with self.assertRaises(Exception):
            validate_vault(tampered["vault"], user_id=tampered["user_id"])
